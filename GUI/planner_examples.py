def run_example(trajectory_func, T_duration, gripper_actions=None, 
                n_waypoints=100, adaptive_sampling=False, use_mu_func=False):
    """Run a trajectory planning example.
    
    Args:
        trajectory_func: Function f(t) -> [x, y, z]
        T_duration: Duration of trajectory in normalized time units
        gripper_actions: Optional dict of time -> gripper angle
        n_waypoints: Number of waypoints to sample from trajectory
        adaptive_sampling: If True, sample more densely where acceleration is high
        use_mu_func: If True, use variable mu function; otherwise mu=0
    """
    # Create planner
    planner = TrajectoryPlanner(
        joints_max_speeds=JOINTS_MAX_SPEEDS,
        joints_max_accel=JOINTS_MAX_ACCEL,
        n_waypoints_input=n_waypoints,
        dt_sample=1e-3,
        inverse_kinematics_func=ik_func,
        mu_func=mu_func if use_mu_func else lambda x,y,z: 0,
        gripper_actions=gripper_actions,
        adaptive_sampling=adaptive_sampling
    )
    
    # Plan trajectory
    print(f"\n{'='*60}")
    print(f"Planning trajectory...")
    print(f"{'='*60}")
    planned_waypoints = planner.plan_trajectory(trajectory_func, T_duration)
    
    # Print summary
    print(f"\n{'='*60}")
    print("Generated Waypoints (Arduino format)")
    print(f"{'='*60}")
    time_us = round(planner.output_waypoint_dt * 1e6)
    output_parts = [f"wn{planner.output_waypoint_count}d{time_us}"]
    
    for waypoint in planned_waypoints:
        theta, alpha, beta, mu, gripper = waypoint
        waypoint_str = f"t{theta:.1f}a{alpha:.1f}b{beta:.1f}m{np.rad2deg(mu):.1f}g{gripper:.1f}"
        output_parts.append(waypoint_str)
    
    output = ",".join(output_parts)
    print(output)
    print(f"{'='*60}\n")
    
    # Show plots
    planner.plot_results(trajectory_func, T_duration)


def run_polyline_example(file_path, polyline_index, gripper_actions=None, 
                         use_mu_func=False):
    """Run a trajectory planning example using an imported polyline.
    
    Args:
        file_path: Path to waypoints file generated by poly_extract.py
        polyline_index: Index of the polyline to use (0-based)
        gripper_actions: Optional dict of normalized time (0 to 1) -> gripper angle
        use_mu_func: If True, use variable mu function; otherwise mu=0
    """
    # Load polyline
    waypoint_list, T_duration = get_polyline_trajectory(file_path, polyline_index)
    
    print(f"\n{'='*60}")
    print(f"Loaded polyline {polyline_index} from: {file_path}")
    print(f"Polyline contains {len(waypoint_list)} waypoints")
    print(f"Suggested duration: {T_duration:.2f}s")
    print(f"{'='*60}")
    
    # Create planner
    planner = TrajectoryPlanner(
        joints_max_speeds=JOINTS_MAX_SPEEDS,
        joints_max_accel=JOINTS_MAX_ACCEL,
        dt_sample=1e-3,
        inverse_kinematics_func=ik_func,
        mu_func=mu_func if use_mu_func else lambda x,y,z: 0,
        gripper_actions=gripper_actions
    )
    
    # Plan trajectory using waypoint list mode
    print(f"\n{'='*60}")
    print(f"Planning trajectory from waypoint list...")
    print(f"{'='*60}")
    planned_waypoints = planner.plan_trajectory(
        waypoint_list=waypoint_list,
        use_waypoint_list=True,
        gripper_actions=gripper_actions
    )
    
    # Print summary
    print(f"\n{'='*60}")
    print("Generated Waypoints (Arduino format)")
    print(f"{'='*60}")
    time_us = round(planner.output_waypoint_dt * 1e6)
    output_parts = [f"wn{planner.output_waypoint_count}d{time_us}"]
    
    for waypoint in planned_waypoints:
        theta, alpha, beta, mu, gripper = waypoint
        waypoint_str = f"t{theta:.1f}a{alpha:.1f}b{beta:.1f}m{np.rad2deg(mu):.1f}g{gripper:.1f}"
        output_parts.append(waypoint_str)
    
    output = ",".join(output_parts)
    print(output)
    print(f"{'='*60}\n")
    
    # Show plots (waypoint list mode doesn't have trajectory_func, so pass None)
    planner.plot_results(None, None)


