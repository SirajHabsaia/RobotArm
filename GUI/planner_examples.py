def lissajous_curve(t, T_total=1.0):
    """Cool Lissajous curve pattern."""
    s = t / T_total
    return [
        400 + 40.0 * np.sin(5.0 * 2*np.pi*s),
        50.0 * np.cos(3.0 * 2*np.pi*s),
        15
    ]


def flower_curve_simple(t, T_total=1.0):
    """Simple flower-like parametric curve."""
    s = t / T_total
    return [
        500 + 25*(np.cos(16*np.pi*s) + 1/2*np.cos(6*np.pi*s) + 1/3*np.sin(10*np.pi*s)),
        25*(np.sin(16*np.pi*s) + 1/2*np.sin(6*np.pi*s) + 1/3*np.cos(10*np.pi*s)),
        20
    ]


def flower_curve_complex(t, T_total=1.0):
    """Complex flower curve using polar rose equations."""
    s = t * 38  # Scale time parameter
    return [
        500 + 3*(11*np.cos(s) - 6*np.cos(11*s/6)),
        3*(11*np.sin(s) - 6*np.sin(11*s/6)),
        18
    ]


