def load_polylines_from_file(file_path):
    """Load all polylines from a waypoints file generated by poly_extract.py.
    
    Args:
        file_path: Path to the waypoints file
        
    Returns:
        List of polylines, where each polyline is a list of (x, y, z) tuples
        Each polyline includes pen lift points at start and end.
    """
    polylines = []
    current_polyline = []
    last_line_was_coordinate = False
    
    with open(file_path, 'r') as f:
        for line in f:
            line = line.strip()
            
            # Skip comments
            if line.startswith('#'):
                continue
            
            # Empty line signals end of polyline
            if not line:
                if current_polyline:
                    polylines.append(current_polyline)
                    current_polyline = []
                last_line_was_coordinate = False
                continue
            
            # Parse coordinate line
            parts = line.split(',')
            if len(parts) == 3:
                try:
                    x = float(parts[0].strip())
                    y = float(parts[1].strip())
                    z = float(parts[2].strip())
                    current_polyline.append((x, y, z))
                    last_line_was_coordinate = True
                except ValueError:
                    continue
    
    # Add any remaining polyline
    if current_polyline:
        polylines.append(current_polyline)
    
    return polylines


def get_polyline_trajectory(file_path, polyline_index):
    """Get a specific polyline from a waypoints file as a trajectory function.
    
    Args:
        file_path: Path to the waypoints file
        polyline_index: Index of the polyline to extract (0-based)
        
    Returns:
        Tuple of (waypoint_list, T_duration) where:
        - waypoint_list: List of (x, y, z) tuples for the polyline (includes pen lift points)
        - T_duration: Suggested duration based on number of points
    """
    polylines = load_polylines_from_file(file_path)
    
    if polyline_index < 0 or polyline_index >= len(polylines):
        raise ValueError(f"Polyline index {polyline_index} out of range. File contains {len(polylines)} polylines.")
    
    waypoint_list = polylines[polyline_index]
    
    # Suggest duration based on number of points (rough estimate)
    T_duration = len(waypoint_list) * 0.02  # 20ms per waypoint
    
    return waypoint_list, T_duration


