def quarter_ellipse(s, xi, yi, zi, xf, yf, zf, n=3):
    """Quarter ellipse from (xi, yi, zi) to (xf, yf, zf).
    
    Args:
        s: Parameter from 0 to 1
        xi, yi, zi: Initial position
        xf, yf, zf: Final position
        n: Shape parameter (higher = more linear, lower = more curved)
    """
    s = 1-(1-s)**n if s>=0 else -1+(1+s)**n
    return [
        xi + (xf - xi) * s,
        yi + (yf - yi) * s,
        zf + (zi - zf) * (1 - abs(s)**n) ** (1/n)
    ]


def semi_ellipse(s, xi, yi, zi, xf, yf, zm, n=3):
    """Semi-ellipse arc from (xi, yi, zi) to (xf, yf, zi) with max height zm.
    
    Args:
        s: Parameter from 0 to 2 (half-ellipse spans two time units)
        xi, yi, zi: Initial position
        xf, yf: Final x, y position (z returns to zi)
        zm: Maximum Z height at the middle of the arc
        n: Shape parameter
    """
    s = s-1
    return quarter_ellipse(s, (xi+xf)/2, (yi+yf)/2, zm, xf, yf, zi, n=n)


